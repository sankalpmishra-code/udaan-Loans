// Helper to search across curated and global databases
export function searchGlobalUniversities(
  query: string,
  countryFilter?: string
): GlobalUniversityEntry[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];

  return globalUniversitiesDatabase.filter((uni) => {
    if (countryFilter && countryFilter !== "all" && uni.country !== countryFilter) {
      return false;
    }
    return (
      uni.name.toLowerCase().includes(q) ||
      uni.shortName.toLowerCase().includes(q) ||
      uni.city.toLowerCase().includes(q) ||
      uni.countryName.toLowerCase().includes(q)
    );
  });
}
